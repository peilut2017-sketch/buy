// Builds one SQL file for a trial run: every migration in order, then the Terminal X rules.
// Paste the output into the Supabase SQL editor (a new, empty project). Usage: node scripts/make-trial-sql.mjs > .trial/setup.sql
import { readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const migrations = readdirSync(resolve(root, "supabase/migrations")).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const quote = (text) => `'${text.replace(/'/g, "''")}'`;
const site = JSON.parse(readFileSync(resolve(root, "packages/adapters/terminalx/site.json"), "utf8"));
const config = JSON.stringify(JSON.parse(readFileSync(resolve(root, "packages/adapters/terminalx/config.json"), "utf8")));

const out = [];
out.push("-- SmartBuy trial setup. Generated by scripts/make-trial-sql.mjs. Run once on an EMPTY Supabase project.");
for (const file of migrations) out.push(`\n-- ===== ${file} =====\n${readFileSync(resolve(root, "supabase/migrations", file), "utf8")}`);
out.push(`\n-- ===== Terminal X rules (from packages/adapters/terminalx/config.json) =====`);
out.push(`update public.sites set adapter_config = ${quote(config)}::jsonb where id = ${quote(site.id)};`);
out.push(`\n-- The trial runs the store as "beta". Change to 'active' when you want the strip without the beta label.`);
out.push(`update public.sites set status = 'beta' where id = ${quote(site.id)};`);
out.push(`\n-- After you sign in once, make yourself the admin (replace the address):`);
out.push(`-- update public.profiles set role = 'admin' where id = (select id from auth.users where email = 'you@example.com');`);
console.log(out.join("\n"));
